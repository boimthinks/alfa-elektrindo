#!/usr/bin/env node
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const PARTS_DIR = join(ROOT, 'src/content/parts');
const TERMS_PATH = join(ROOT, 'src/lib/autolink-terms.ts');

function readBlockScalar(content, key) {
  const m = content.match(new RegExp(`^${key}:\\s*\\|-\\s*\\n\\s*([^\\n]+)`, 'm'));
  return m ? m[1].trim() : null;
}

const categories = new Set();
const manufacturers = new Set();
const skipList = [
  'sensor', 'switch', 'diode', 'capacitor', 'controller', 'drive', 
  'relay', 'module', 'data', 'power', 'filter', 'input', 'output'
];

for (const file of readdirSync(PARTS_DIR).filter(f => f.endsWith('.md'))) {
  const content = readFileSync(join(PARTS_DIR, file), 'utf8');
  const cat = readBlockScalar(content, 'category');
  const man = readBlockScalar(content, 'manufacturer');
  if (cat) categories.add(cat);
  if (man) manufacturers.add(man);
}

const catTerms = [...categories].filter(c => !skipList.includes(c.toLowerCase())).map(c => ({
  name: c,
  slug: `/ca/${c.toLowerCase().replace(/[^a-z0-9]+/g, '-')}/`
}));

const manTerms = [...manufacturers].filter(m => !skipList.includes(m.toLowerCase())).map(m => ({
  name: m,
  slug: `/ma/${m.toLowerCase().replace(/[^a-z0-9]+/g, '-')}/`
}));

const content = `// Auto-generated by scripts/gen-autolink-terms.js
export const categories = ${JSON.stringify(catTerms, null, 2)};
export const manufacturers = ${JSON.stringify(manTerms, null, 2)};
export const skipList = ${JSON.stringify(skipList, null, 2)};
`;

writeFileSync(TERMS_PATH, content, 'utf8');
console.log('src/lib/autolink-terms.ts generated successfully.');
